package com.util.api.generico;

public class TriplaDTO {

    public Integer primero;
    public Double segundo;
    public String tercero;

    public TriplaDTO() {
    }

    public TriplaDTO(Integer primero, Double segundo, String tercero) {
        this.primero = primero;
        this.segundo = segundo;
        this.tercero = tercero;
    }
}